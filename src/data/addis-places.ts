export function searchAddisPlaces(query: string, limit = 7) {
  const normalized = query.trim().toLowerCase();
  const source = normalized
    ? addisPlaceIndex.filter((place) =>
        [place.name, place.context, ...(place.aliases ?? [])]
          .join(" ")
          .toLowerCase()
          .includes(normalized),
      )
    : popularAddisPlaces
        .map((name) => addisPlaceIndex.find((place) => place.name === name))
        .filter((place): place is AddisPlace => Boolean(place));

  return source.slice(0, limit);
}
